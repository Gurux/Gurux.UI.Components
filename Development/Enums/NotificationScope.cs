namespace Gurux.UI.Components.Enums
{
    /// <summary>
    /// Defines whether a notification belongs to a page or the entire application.
    /// </summary>
    public enum NotificationScope
    {
        /// <summary>
        /// Associates the notification with the current page.
        /// </summary>
        Page,
        /// <summary>
        /// Associates the notification with the entire application.
        /// </summary>
        Global
    }
}